import json
from datetime import datetime, timezone

import joblib
import numpy as np
import pandas as pd
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    roc_auc_score,
)

from config.paths_config import (
    BASELINE_DATA_PATH,
    NEW_BATCH_DATA_PATH,
    MODEL_PATH,
    PREPROCESSOR_PATH,
    REPORTS_DIR,
    MONITORING_REPORT_PATH,
    create_project_directories,
)


class ModelMonitor:
    """
    Evaluates the saved model on a new batch and combines its results
    with the data-drift report generated by src.data_drift.DataDrift.
    """

    def __init__(self, target_column="target", f1_drop_threshold=0.05):
        self.target_column = target_column
        self.f1_drop_threshold = f1_drop_threshold

    @staticmethod
    def _load_json(path):
        if not path.exists():
            raise FileNotFoundError(
                f"Required report not found: {path}. Run the earlier project steps first."
            )
        with open(path, "r", encoding="utf-8") as file:
            return json.load(file)

    def _load_inputs(self):
        required_files = [
            BASELINE_DATA_PATH,
            NEW_BATCH_DATA_PATH,
            MODEL_PATH,
            PREPROCESSOR_PATH,
        ]
        for path in required_files:
            if not path.exists():
                raise FileNotFoundError(
                    f"Required file not found: {path}. Complete the previous steps first."
                )

        baseline_df = pd.read_csv(BASELINE_DATA_PATH)
        new_batch_df = pd.read_csv(NEW_BATCH_DATA_PATH)

        if baseline_df.empty or new_batch_df.empty:
            raise ValueError("Baseline data and new batch must not be empty.")

        if self.target_column not in baseline_df.columns:
            raise ValueError(f"'{self.target_column}' is missing from baseline data.")
        if self.target_column not in new_batch_df.columns:
            raise ValueError(f"'{self.target_column}' is missing from new batch data.")

        X_new = new_batch_df.drop(columns=[self.target_column])
        y_new = new_batch_df[self.target_column]

        baseline_features = [
            col for col in baseline_df.columns if col != self.target_column
        ]
        if list(X_new.columns) != baseline_features:
            raise ValueError(
                "New-batch feature columns or their order do not match baseline data."
            )

        if y_new.isnull().any():
            raise ValueError("New-batch target contains missing values.")

        model = joblib.load(MODEL_PATH)
        preprocessor = joblib.load(PREPROCESSOR_PATH)

        return X_new, y_new, model, preprocessor

    def evaluate_new_batch(self):
        X_new, y_new, model, preprocessor = self._load_inputs()

        # Use the already-fitted training preprocessor. Do not fit it on new data.
        transformed = preprocessor.transform(X_new)

        # Preserve feature names to avoid sklearn's "valid feature names" warning.
        feature_names = getattr(preprocessor, "feature_names_in_", X_new.columns)
        X_processed = pd.DataFrame(
            transformed,
            columns=list(feature_names),
            index=X_new.index,
        )

        predictions = model.predict(X_processed)

        if not hasattr(model, "predict_proba"):
            raise AttributeError(
                "The saved model does not support predict_proba(), which is required "
                "to calculate ROC-AUC in this monitoring implementation."
            )

        probabilities = model.predict_proba(X_processed)
        classes = list(getattr(model, "classes_", []))
        if 1 not in classes:
            raise ValueError(
                "The saved model does not contain class 1; expected target labels 0 and 1."
            )
        positive_class_index = classes.index(1)
        positive_probabilities = probabilities[:, positive_class_index]

        metrics = {
            "accuracy": float(accuracy_score(y_new, predictions)),
            "precision": float(
                precision_score(y_new, predictions, zero_division=0)
            ),
            "recall": float(recall_score(y_new, predictions, zero_division=0)),
            "f1_score": float(f1_score(y_new, predictions, zero_division=0)),
            "roc_auc": (
                float(roc_auc_score(y_new, positive_probabilities))
                if y_new.nunique() == 2
                else None
            ),
        }

        return {
            "model_name": type(model).__name__,
            "new_batch_rows": int(len(X_new)),
            "positive_class": "benign (1)",
            "metrics": metrics,
        }

    def build_monitoring_report(self):
        create_project_directories()

        baseline_report_path = REPORTS_DIR / "baseline_evaluation_report.json"
        drift_report_path = REPORTS_DIR / "drift_report.json"

        baseline_report = self._load_json(baseline_report_path)

        # Step 9 method name is initiate_drift_detection().
        # Run it here so this file also refreshes the drift report.
        from src.data_drift import DataDrift

        drift_detector = DataDrift()
        drift_detector.initiate_drift_detection()

        drift_report = self._load_json(drift_report_path)

        new_batch_evaluation = self.evaluate_new_batch()

        baseline_metrics = baseline_report.get("metrics", {})
        if not baseline_metrics:
            raise ValueError(
                "The baseline evaluation JSON does not contain a 'metrics' object. "
                "Check artifacts/reports/baseline_evaluation_report.json."
            )

        new_metrics = new_batch_evaluation["metrics"]
        baseline_f1 = baseline_metrics.get("f1_score")
        if baseline_f1 is None:
            raise ValueError("Baseline report is missing the 'f1_score' metric.")

        f1_drop = float(baseline_f1) - float(new_metrics["f1_score"])
        performance_alert = f1_drop > self.f1_drop_threshold

        drift_alert = bool(drift_report.get("drift_detected", False))
        overall_status = (
            "ALERT" if drift_alert or performance_alert else "HEALTHY"
        )

        metric_comparison = {}
        for metric_name, new_value in new_metrics.items():
            baseline_value = baseline_metrics.get(metric_name)
            metric_comparison[metric_name] = {
                "baseline": (
                    float(baseline_value) if baseline_value is not None else None
                ),
                "new_batch": (
                    float(new_value) if new_value is not None else None
                ),
                "difference": (
                    float(new_value) - float(baseline_value)
                    if new_value is not None and baseline_value is not None
                    else None
                ),
            }

        report = {
            "generated_at_utc": datetime.now(timezone.utc).isoformat(),
            "status": overall_status,
            "alerts": {
                "data_drift": drift_alert,
                "performance_degradation": bool(performance_alert),
            },
            "model_evaluation": {
                **new_batch_evaluation,
                "baseline_metrics": {
                    key: (
                        float(value) if value is not None else None
                    )
                    for key, value in baseline_metrics.items()
                    if key in new_metrics
                },
                "new_batch_metrics": new_metrics,
                "metric_comparison": metric_comparison,
                "f1_drop": f1_drop,
                "f1_drop_threshold": self.f1_drop_threshold,
                "performance_alert": bool(performance_alert),
            },
            "data_drift": {
                "method": drift_report.get("method"),
                "total_features": drift_report.get("total_features"),
                "drifted_features": drift_report.get("drifted_features"),
                "drift_percentage": drift_report.get("drift_percentage"),
                "drift_detected": drift_alert,
                "feature_results": drift_report.get("feature_results", []),
            },
            "data_note": (
                "The incoming batch is simulated from the reference dataset. "
                "Its retained labels are used only to demonstrate offline "
                "monitoring; they are not independently collected production outcomes."
            ),
        }

        with open(MONITORING_REPORT_PATH, "w", encoding="utf-8") as file:
            json.dump(report, file, indent=4, allow_nan=False)

        print("\nModel evaluation completed successfully.")
        print("Data drift detection completed successfully.")
        print("Baseline F1-score:", round(float(baseline_f1), 4))
        print("New-batch F1-score:", round(float(new_metrics["f1_score"]), 4))
        print("F1-score drop:", round(f1_drop, 4))
        print("Data drift alert:", drift_alert)
        print("Performance alert:", bool(performance_alert))
        print("Monitoring status:", overall_status)
        print("Monitoring report saved:", MONITORING_REPORT_PATH)

        return report

    def run(self):
        print("Starting monitoring pipeline...")
        return self.build_monitoring_report()
