import joblib
import pandas as pd

from sklearn.impute import SimpleImputer
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler

from config.paths_config import (
    DATA_DIR,
    MODELS_DIR,
    create_project_directories,
)


class DataPreprocessing:
    """
    Preprocess training and testing features without data leakage.

    The imputer and scaler are fitted only on X_train.
    The same fitted pipeline is then used to transform X_test.
    Target columns are not scaled or imputed by this class.
    """

    def __init__(self, strategy="median"):
        self.strategy = strategy
        self.preprocessor = Pipeline(
            steps=[
                ("imputer", SimpleImputer(strategy=self.strategy)),
                ("scaler", StandardScaler()),
            ]
        )

    def load_data(self):
        """Load the four datasets generated by Step 3."""
        required_files = {
            "X_train": DATA_DIR / "X_train.csv",
            "X_test": DATA_DIR / "X_test.csv",
            "y_train": DATA_DIR / "y_train.csv",
            "y_test": DATA_DIR / "y_test.csv",
        }

        missing_files = [
            str(path) for path in required_files.values() if not path.exists()
        ]

        if missing_files:
            raise FileNotFoundError(
                "Required Step 3 files are missing:\n" + "\n".join(missing_files)
                + "\nRun python -m src.data_ingestion first."
            )

        X_train = pd.read_csv(required_files["X_train"])
        X_test = pd.read_csv(required_files["X_test"])
        y_train = pd.read_csv(required_files["y_train"])
        y_test = pd.read_csv(required_files["y_test"])

        if X_train.empty or X_test.empty:
            raise ValueError("Training or testing feature data is empty.")

        if list(X_train.columns) != list(X_test.columns):
            raise ValueError(
                "Training and testing feature columns do not match."
            )

        if len(X_train) != len(y_train) or len(X_test) != len(y_test):
            raise ValueError("Feature and target row counts do not match.")

        print("Training and testing datasets loaded successfully.")
        print("X_train shape:", X_train.shape)
        print("X_test shape:", X_test.shape)

        return X_train, X_test, y_train, y_test

    def check_missing_values(self, X_train, X_test):
        """Display missing-value counts before preprocessing."""
        print("\nMissing values in training data:")
        print(X_train.isnull().sum().sum())

        print("Missing values in testing data:")
        print(X_test.isnull().sum().sum())

    def fit_transform_training_data(self, X_train):
        """Fit imputer/scaler on training data and transform it."""
        transformed = self.preprocessor.fit_transform(X_train)

        X_train_processed = pd.DataFrame(
            transformed,
            columns=X_train.columns,
            index=X_train.index,
        )

        print("\nPreprocessor fitted on training data.")
        return X_train_processed

    def transform_testing_data(self, X_test):
        """Transform test data using the already-fitted training pipeline."""
        transformed = self.preprocessor.transform(X_test)

        X_test_processed = pd.DataFrame(
            transformed,
            columns=X_test.columns,
            index=X_test.index,
        )

        print("Testing data transformed using training preprocessor.")
        return X_test_processed

    def save_preprocessor(self):
        """Persist the fitted preprocessing pipeline."""
        create_project_directories()
        preprocessor_path = MODELS_DIR / "preprocessor.pkl"

        joblib.dump(self.preprocessor, preprocessor_path)

        print("Preprocessor saved at:", preprocessor_path)
        return preprocessor_path

    def save_processed_data(
        self, X_train_processed, X_test_processed, y_train, y_test
    ):
        """Save processed features and unchanged target labels."""
        create_project_directories()

        X_train_path = DATA_DIR / "X_train_processed.csv"
        X_test_path = DATA_DIR / "X_test_processed.csv"
        y_train_path = DATA_DIR / "y_train_processed.csv"
        y_test_path = DATA_DIR / "y_test_processed.csv"

        X_train_processed.to_csv(X_train_path, index=False)
        X_test_processed.to_csv(X_test_path, index=False)

        # Labels are not scaled; save copies for a consistent processed-data set.
        y_train.to_csv(y_train_path, index=False)
        y_test.to_csv(y_test_path, index=False)

        print("\nProcessed datasets saved:")
        print(X_train_path)
        print(X_test_path)
        print(y_train_path)
        print(y_test_path)

    def initiate_data_preprocessing(self):
        """Execute the complete preprocessing workflow."""
        X_train, X_test, y_train, y_test = self.load_data()

        self.check_missing_values(X_train, X_test)

        X_train_processed = self.fit_transform_training_data(X_train)
        X_test_processed = self.transform_testing_data(X_test)

        self.save_preprocessor()

        self.save_processed_data(
            X_train_processed,
            X_test_processed,
            y_train,
            y_test,
        )

        print("\nData preprocessing completed successfully.")

        return (
            X_train_processed,
            X_test_processed,
            y_train,
            y_test,
        )


if __name__ == "__main__":
    preprocessing = DataPreprocessing(strategy="median")
    preprocessing.initiate_data_preprocessing()
